"""Command-line interface for running and replaying the example workflow."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .contracts import ContractError
from .workflow import RunAlreadyExistsError, replay_workflow, run_workflow, verify_integrity


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="workflow-audit", description="Run and replay a local auditable workflow.")
    subparsers = parser.add_subparsers(dest="command", required=True)

    run_parser = subparsers.add_parser("run", help="execute a fixture-driven workflow")
    run_parser.add_argument("--fixture", type=Path, required=True, help="path to a local JSON fixture")
    run_parser.add_argument("--run-dir", type=Path, required=True, help="new directory for saved run artifacts")
    run_parser.add_argument("--run-id", default=None, help="optional stable run ID (generated by default)")
    run_parser.add_argument("--config", type=Path, default=None, help="optional local config JSON")

    replay_parser = subparsers.add_parser("replay", help="verify integrity and replay a saved run")
    replay_parser.add_argument("--run-dir", type=Path, required=True, help="directory containing audit.json")

    verify_parser = subparsers.add_parser("verify", help="verify hashes without executing operations")
    verify_parser.add_argument("--run-dir", type=Path, required=True, help="directory containing audit.json")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "run":
            manifest = run_workflow(args.fixture, args.run_dir, args.run_id, args.config)
            print(json.dumps({
                "run_id": manifest["run_id"],
                "status": manifest["status"],
                "operations_recorded": len(manifest["operations"]),
                "audit_file": str(args.run_dir / "audit.json"),
            }, indent=2))
            return 0 if manifest["status"] == "success" else 2

        if args.command == "verify":
            failures = verify_integrity(args.run_dir)
            report = {"status": "pass" if not failures else "fail", "failures": failures}
            print(json.dumps(report, indent=2))
            return 0 if not failures else 3

        result = replay_workflow(args.run_dir)
        print(json.dumps(result.to_dict(), indent=2))
        return 0 if result.status == "match" else 3
    except (ContractError, RunAlreadyExistsError) as exc:
        print(json.dumps({"error": exc.__class__.__name__, "message": str(exc)}, indent=2), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
